#!/usr/bin/env python3
"""Per-group scenario parameters for CA2, Computer Networks, Fall 1405.

Usage:  python3 ca2_params.py <student-id> [<student-id> ...]

Writes params.ini (already included by every phase's omnetpp.ini) and
params.json (read by the analysis code) next to this script, and prints the
table that goes at the top of the report.
The values depend only on the set of student IDs, so TAs can regenerate them.
"""
import hashlib
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# name -> (allowed values, unit, meaning)
PHASE1 = {
    "L":     (list(range(400, 1501, 50)), "B",    "payload per frame"),   # 1500 is re-picked, see pick()
    "R":     ([12, 18, 24, 36, 48, 54],   "Mbps", "data bitrate (802.11a)"),
}
PHASE2 = {
    "n2":    ([4, 5, 6],                  "",     "stations in phase 2 (host[0] is the slow one)"),
    "Rslow": ([6, 9, 12],                 "Mbps", "bitrate of the slow station"),
    "Rfast": ([36, 48, 54],               "Mbps", "bitrate of the other stations"),
}
PHASE3 = {
    "alpha": ([2.8, 3.0, 3.2, 3.4],         "",     "path-loss exponent"),
    "sigma": ([3, 4, 5],                    "dB",   "shadowing standard deviation"),
    "v":     ([1.0, 1.25, 1.5, 1.75, 2.0],  "m/s",  "walking speed"),
    "BI":    ([100, 150, 200],              "ms",   "beacon interval of both APs"),
    "nCh":   ([4, 5, 6, 7, 8],              "",     "channels the station scans (0 .. nCh-1)"),
}
PARAMS = {**PHASE1, **PHASE2, **PHASE3}
# name -> (unit, meaning); computed from the parameters above
DERIVED = {
    "D":     ("m",    "distance between the two APs (phase 3)"),
}


# Largest payload that phase 2 can carry: L plus the UDP and IP headers (28 B)
# must fit in one Ethernet frame (1500 B) on the link between the server and the AP.
L_MAX = 1450


def pick(ids, name, values):
    key = "CA2-1405|" + "|".join(ids) + "|" + name
    h = int.from_bytes(hashlib.sha256(key.encode()).digest(), "big")
    value = values[h % len(values)]
    if name == "L" and value > L_MAX:
        # a second pick among the values that fit; every other group keeps its first pick
        value = pick(ids, name + "|2", [v for v in values if v <= L_MAX])
    return value


def ap_spacing(alpha):
    """1.25 times the distance at which the mean power received from an AP (20 mW, 5.03 GHz,
    log-distance path loss from d0 = 1 m) falls to the -85 dBm receiver sensitivity."""
    pl_d0 = 20 * math.log10(4 * math.pi * 5.03e9 / 299792458)
    reach = 10 ** ((10 * math.log10(20) - pl_d0 + 85) / (10 * alpha))
    return round(1.25 * reach)


def derived(p):
    return {"D": ap_spacing(p["alpha"])}


def ini_text(p, ids):
    """params.ini for every phase; each line names its network, so a phase only sees its own lines."""
    D = derived(p)["D"]
    return "\n".join([
        f"# generated by ca2_params.py for {' '.join(ids)}; do not edit",
        f"Contention.**.wlan*.bitrate = {p['R']}Mbps",
        f"Contention.**.cli.reqLength = {p['L']}B",
        f"Anomaly.n = {p['n2']}",
        f"Anomaly.host[0].wlan[*].bitrate = {p['Rslow']}Mbps",
        f"Anomaly.host[*].wlan[*].bitrate = {p['Rfast']}Mbps",
        f"Anomaly.ap.wlan[*].bitrate = {p['Rfast']}Mbps",
        f"Anomaly.**.messageLength = {p['L']}B",
        f"Anomaly.ap.**.pendingQueue.numQueues = {p['n2']}",
        f"Roaming.D = {D}m",
        f"Roaming.radioMedium.pathLoss.alpha = {p['alpha']}",
        f"Roaming.radioMedium.pathLoss.sigma = {p['sigma']}",
        f"Roaming.ap*.wlan.mgmt.beaconInterval = {p['BI']}ms",
        f"Roaming.host.wlan.mgmt.numChannels = {p['nCh']}",
        # start 2 m beside ap1, walk D metres along +x at v, then stand still next to ap2
        f"Roaming.*.mobility.turtleScript = xml(\"<movement><set x='50' y='102' speed='{p['v']}' angle='0'/>"
        f"<forward d='{D}'/></movement>\")",
    ]) + "\n"


def main():
    ids = sorted({a.strip() for a in sys.argv[1:]})
    if not ids or not all(i.isdigit() and len(i) == 9 for i in ids):
        sys.exit("usage: python3 ca2_params.py <9-digit student id> [...]")
    p = {name: pick(ids, name, vals) for name, (vals, _, _) in PARAMS.items()}

    with open(os.path.join(HERE, "params.ini"), "w") as f:
        f.write(ini_text(p, ids))
    with open(os.path.join(HERE, "params.json"), "w") as f:
        json.dump({"students": ids, **p, **derived(p)}, f, indent=2)

    print(f"students: {', '.join(ids)}")
    print("| param | value | meaning |\n|---|---|---|")
    for name, (_, unit, meaning) in PARAMS.items():
        print(f"| {name} | {p[name]} {unit} | {meaning} |")
    for name, value in derived(p).items():
        unit, meaning = DERIVED[name]
        print(f"| {name} | {value} {unit} | {meaning} |")


if __name__ == "__main__":
    main()
